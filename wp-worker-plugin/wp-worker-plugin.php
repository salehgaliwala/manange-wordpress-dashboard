    private function recursive_cleanup($dir) {
        if (!file_exists($dir)) {
            return;
        }
        $files = array_diff(scandir($dir), array('.', '..'));
        foreach ($files as $file) {
            $path = $dir . '/' . $file;
            if (is_dir($path)) {
                $this->recursive_cleanup($path);
            } else {
                unlink($path);
            }
        }
        rmdir($dir);
    }
